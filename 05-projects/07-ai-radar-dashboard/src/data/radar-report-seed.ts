import {
  MONITOR_POOL_LABELS,
  RESEARCH_SOURCES,
  type MonitorPool,
} from "@/data/research-sources";
import type { RadarDailyReport, RadarSignal } from "@/lib/radar-types";

function poolsMeta() {
  const pools = Object.keys(MONITOR_POOL_LABELS) as MonitorPool[];
  return pools.map((pool) => ({
    pool,
    label: MONITOR_POOL_LABELS[pool],
    sourceCount: RESEARCH_SOURCES.filter((s) => s.pool === pool).length,
  }));
}

