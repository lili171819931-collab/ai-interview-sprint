/** 替换模板中的 {key} 占位符 */
export function interpolate(
  template: string,
  values?: Record<string, string | number>,
): string {
  const v = values || {};
  return template.replace(/\{(\w+)\}/g, (raw, key: string) =>
    key in v ? String(v[key]) : raw,
  );
}
