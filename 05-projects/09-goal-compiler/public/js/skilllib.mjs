/**
 * skilllib.mjs — 一键导出可安装 SKILL.md（竞品启示：与 khazix/superpowers 生态打通）
 * 把编译结果生成「可直接安装到 .claude/skills 或 .codex/skills」的 SKILL.md。
 * 纯函数，可测试。
 */
export function buildSkillMd(result, opts = {}) {
  const a = result.analysis;
  const subject = a.entities.object || 'goal';
  const safeName = (subject.replace(/[^\w\u4e00-\u9fff]/g, '-').slice(0, 24)) || 'goal-compiler';
  const lang = opts.lang === 'en' ? 'en' : 'zh';
  const goal = lang === 'en' ? result.goalPromptEn : result.goalPrompt;
  const desc = lang === 'en'
    ? `Compile a vague idea ("${subject}") into an executable, verifiable task spec for AI agents. Use when the user wants a goal/task brief for an agent.`
    : `把一句模糊想法（「${subject}」）编译成 AI agent 可独立执行、可验收的目标任务书。用户说「帮我拆解这个目标 / 写个任务书给 agent / 写个 goal 提示词」时使用。`;

  return `---
name: ${safeName}
description: ${desc}
---

# ${lang === 'en' ? 'Goal' : '目标'}：${subject}

${lang === 'en' ? 'This skill was generated by Goal Compiler. Paste the body below into your agent goal mode, or use it as a standalone task brief.' : '本技能由 Goal Compiler 生成。可直接粘贴到 Agent 的 /goal 目标模式，或作为独立任务书使用。'}

---

${goal}
`;
}

export function skillFilename(result) {
  const a = result.analysis;
  const subject = (a.entities.object || 'goal').replace(/[^\w\u4e00-\u9fff]/g, '-').slice(0, 24);
  return `${subject}-SKILL.md`;
}

export default { buildSkillMd, skillFilename };
